-- Suporte RN Integra, fase 1: equipe da plataforma, 2FA e registro de auditoria.
-- A equipe de suporte é da plataforma (acima das organizações), não um papel dentro da clínica.
-- Entrar ou sair da equipe é só por SQL/migração: não existe tela para alguém se promover.

create table if not exists public.platform_staff(
  user_id bigint primary key references public.users(id) on delete cascade,
  role text not null default 'support' check (role in ('support')),
  active boolean not null default true,
  -- Segredo do autenticador (TOTP), cifrado pela aplicação (AES-GCM); nunca em texto puro.
  mfa_secret_enc text,
  -- Preenchido quando o primeiro código é confirmado; até lá o 2FA está só em configuração.
  mfa_enabled_at timestamptz,
  -- Último intervalo de 30 s aceito: o mesmo código não serve duas vezes.
  mfa_last_step bigint,
  note text check (note is null or char_length(note) <= 200),
  created_at timestamptz not null default now()
);

-- Ações do suporte: só acrescenta. Nem o servidor altera ou apaga o que já foi gravado.
create table if not exists public.support_audit(
  id bigint generated by default as identity primary key,
  staff_user_id bigint not null references public.users(id),
  action text not null check (char_length(action) between 1 and 80),
  organization_id uuid references public.organizations(id),
  target text check (target is null or char_length(target) <= 200),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists support_audit_created_idx on public.support_audit(created_at desc);
create index if not exists support_audit_organization_idx on public.support_audit(organization_id, created_at desc) where organization_id is not null;

-- 2FA vale por sessão: um novo login pede o código de novo.
alter table public.sessions add column if not exists mfa_verified_at timestamptz;

alter table public.platform_staff enable row level security;
alter table public.support_audit enable row level security;

revoke all on public.platform_staff from public, anon, authenticated;
revoke all on public.support_audit from public, anon, authenticated;
grant select, insert, update, delete on public.platform_staff to service_role;
revoke all on public.support_audit from service_role;
grant select, insert on public.support_audit to service_role;
