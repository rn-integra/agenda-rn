-- Suporte RN Integra, fase 5: acesso assistido com autorização da gerência.
-- A gerência libera o suporte por um tempo (até 24 h). Enquanto valer, alguém da equipe de suporte
-- abre uma sessão "assistida": vê o sistema como a gerência que liberou, só para leitura
-- (o servidor recusa qualquer gravação). Encerrar a liberação derruba a sessão na hora.

create table if not exists public.support_access_grants(
  id bigint generated by default as identity primary key,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  granted_by bigint not null references public.users(id),
  reason text check (reason is null or char_length(reason) <= 200),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  revoked_at timestamptz,
  revoked_by bigint references public.users(id),
  constraint support_access_grants_window check (expires_at > created_at and expires_at <= created_at + interval '24 hours 1 minute')
);
create index if not exists support_access_grants_org_idx on public.support_access_grants(organization_id, created_at desc);

-- Sessão assistida: pertence à gerência que liberou (user_id), mas guarda quem do suporte está usando.
alter table public.sessions add column if not exists support_grant_id bigint references public.support_access_grants(id) on delete cascade;
alter table public.sessions add column if not exists support_staff_id bigint references public.users(id) on delete cascade;
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'sessions_support_pair') then
    alter table public.sessions add constraint sessions_support_pair check ((support_grant_id is null) = (support_staff_id is null));
  end if;
end $$;
create index if not exists sessions_support_grant_idx on public.sessions(support_grant_id) where support_grant_id is not null;

alter table public.support_access_grants enable row level security;
revoke all on public.support_access_grants from public, anon, authenticated;
revoke all on public.support_access_grants from service_role;
grant select, insert, update on public.support_access_grants to service_role;

-- Contexto de uma sessão assistida: só vale com liberação ativa, na mesma organização, dada por quem
-- ainda é gerente ali, e com a pessoa do suporte ainda ativa na equipe. Fora disso, null.
create or replace function public.assisted_session_context(p_token_hash text)
returns jsonb
language plpgsql
stable
set search_path = ''
as $$
declare
  v_session public.sessions%rowtype;
  v_grant public.support_access_grants%rowtype;
  v_context jsonb;
  v_staff text;
begin
  if p_token_hash is null or length(p_token_hash) > 100 then return null; end if;
  select s.* into v_session from public.sessions s
    where s.token_hash = p_token_hash and s.expires_at > now() and s.support_grant_id is not null;
  if not found then return null; end if;
  select g.* into v_grant from public.support_access_grants g
    where g.id = v_session.support_grant_id and g.revoked_at is null and g.expires_at > now()
      and g.organization_id = v_session.organization_id and g.granted_by = v_session.user_id;
  if not found then return null; end if;
  select u.name into v_staff from public.platform_staff p join public.users u on u.id = p.user_id
    where p.user_id = v_session.support_staff_id and p.active and u.active;
  if not found then return null; end if;
  v_context := public.session_context(p_token_hash);
  if v_context is null
    or (v_context->'organization'->>'id')::uuid is distinct from v_grant.organization_id
    or v_context->'account'->>'role' is distinct from 'general_manager' then
    return null;
  end if;
  return v_context || jsonb_build_object('assist', jsonb_build_object(
    'staffId', v_session.support_staff_id, 'staffName', v_staff, 'grantId', v_grant.id,
    'expiresAt', least(v_session.expires_at, v_grant.expires_at)));
end;
$$;

revoke all on function public.assisted_session_context(text) from public, anon, authenticated;
grant execute on function public.assisted_session_context(text) to service_role;
