-- Suporte RN Integra: contas próprias da equipe, separadas das contas das clínicas.
-- Quem é do suporte não precisa (nem deve) ter cadastro de clínica, organização, Hub ou agenda.
-- A conta do suporte tem e-mail, senha e autenticador próprios; entra por /suporte/entrar e só vê o console.
-- Contas são criadas só pela equipe da plataforma, por SQL (public.support_staff_invite), que devolve
-- um link de primeiro acesso de uso único: a própria pessoa cria a senha e configura o autenticador.
--
-- Conversão: cada pessoa de public.platform_staff vira uma conta em public.support_staff com o MESMO id
-- (o segredo do autenticador é cifrado com o id, e o registro do suporte já aponta para esses ids).
-- As senhas não são copiadas: cada pessoa recebe um link de primeiro acesso.

create table if not exists public.support_staff(
  id bigint generated by default as identity primary key,
  email text not null check (char_length(email) between 3 and 254 and email = lower(email)),
  name text not null check (char_length(name) between 1 and 120),
  password_hash text,
  password_salt text,
  active boolean not null default true,
  -- Segredo do autenticador (TOTP), cifrado pela aplicação (AES-GCM); nunca em texto puro.
  mfa_secret_enc text,
  mfa_enabled_at timestamptz,
  mfa_last_step bigint,
  note text check (note is null or char_length(note) <= 200),
  created_at timestamptz not null default now(),
  last_login_at timestamptz
);
create unique index if not exists support_staff_email_key on public.support_staff(email);

-- Sessões do console (cookie próprio). O 2FA vale por sessão, por até 12 h.
create table if not exists public.support_sessions(
  token_hash text primary key,
  staff_id bigint not null references public.support_staff(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  mfa_verified_at timestamptz
);
create index if not exists support_sessions_staff_idx on public.support_sessions(staff_id);

-- Links de primeiro acesso (ou de nova senha), de uso único. Só o resumo (sha256) do token fica no banco.
create table if not exists public.support_setup_tokens(
  token_hash text primary key,
  staff_id bigint not null references public.support_staff(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  used_at timestamptz
);
create index if not exists support_setup_tokens_staff_idx on public.support_setup_tokens(staff_id);

-- Conversão das contas antigas (só roda enquanto public.platform_staff existir).
do $$
begin
  if to_regclass('public.platform_staff') is null then return; end if;

  insert into public.support_staff(id, email, name, active, mfa_secret_enc, mfa_enabled_at, mfa_last_step, note, created_at)
    select p.user_id, lower(u.email), left(coalesce(nullif(u.name, ''), u.email), 120), p.active and u.active,
      p.mfa_secret_enc, p.mfa_enabled_at, p.mfa_last_step, p.note, p.created_at
    from public.platform_staff p join public.users u on u.id = p.user_id
    on conflict (id) do nothing;

  -- Quem aparece no registro, em chamados ou em sessões assistidas mas já não está na equipe: conta inativa.
  insert into public.support_staff(id, email, name, active)
    select u.id, lower(u.email), left(coalesce(nullif(u.name, ''), u.email), 120), false
    from public.users u
    where u.id in (
      select staff_user_id from public.support_audit
      union select assigned_staff_id from public.support_tickets where assigned_staff_id is not null
      union select author_user_id from public.support_ticket_messages where from_support
      union select support_staff_id from public.sessions where support_staff_id is not null)
    and not exists (select 1 from public.support_staff s where s.id = u.id)
    on conflict do nothing;

  drop table public.platform_staff;
end $$;

-- Contas novas não reaproveitam ids antigos.
select setval(pg_get_serial_sequence('public.support_staff', 'id'),
  greatest((select coalesce(max(id), 0) from public.support_staff), 100));

-- Registro do suporte: passa a apontar para a conta do suporte. Só a referência muda (nenhuma linha é
-- alterada; a trava de "só acrescenta" continua valendo).
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'support_audit' and column_name = 'staff_user_id') then
    alter table public.support_audit drop constraint if exists support_audit_staff_user_id_fkey;
    alter table public.support_audit rename column staff_user_id to staff_id;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'support_audit_staff_id_fkey') then
    alter table public.support_audit add constraint support_audit_staff_id_fkey foreign key (staff_id) references public.support_staff(id);
  end if;
end $$;
create index if not exists support_audit_staff_idx on public.support_audit(staff_id, created_at desc);

-- Responsável pelo chamado e sessões assistidas: contas do suporte.
alter table public.support_tickets drop constraint if exists support_tickets_assigned_staff_id_fkey;
alter table public.support_tickets add constraint support_tickets_assigned_staff_id_fkey foreign key (assigned_staff_id) references public.support_staff(id);
alter table public.sessions drop constraint if exists sessions_support_staff_id_fkey;
alter table public.sessions add constraint sessions_support_staff_id_fkey foreign key (support_staff_id) references public.support_staff(id) on delete cascade;

-- Mensagens de chamado: quem é da clínica fica em author_user_id; quem é do suporte, em author_staff_id.
alter table public.support_ticket_messages add column if not exists author_staff_id bigint references public.support_staff(id);
alter table public.support_ticket_messages alter column author_user_id drop not null;
update public.support_ticket_messages set author_staff_id = author_user_id, author_user_id = null
  where from_support and author_staff_id is null and author_user_id is not null;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'support_ticket_messages_author') then
    alter table public.support_ticket_messages add constraint support_ticket_messages_author check (
      (from_support and author_staff_id is not null and author_user_id is null)
      or (not from_support and author_user_id is not null and author_staff_id is null));
  end if;
end $$;

-- Sessão assistida: a pessoa do suporte precisa ter conta ativa.
create or replace function public.assisted_session_context(p_token_hash text)
returns jsonb
language plpgsql
stable
set search_path = ''
as $$
declare
  v_session public.sessions%rowtype;
  v_grant public.support_access_grants%rowtype;
  v_context jsonb;
  v_staff text;
begin
  if p_token_hash is null or length(p_token_hash) > 100 then return null; end if;
  select s.* into v_session from public.sessions s
    where s.token_hash = p_token_hash and s.expires_at > now() and s.support_grant_id is not null;
  if not found then return null; end if;
  select g.* into v_grant from public.support_access_grants g
    where g.id = v_session.support_grant_id and g.revoked_at is null and g.expires_at > now()
      and g.organization_id = v_session.organization_id and g.granted_by = v_session.user_id;
  if not found then return null; end if;
  select st.name into v_staff from public.support_staff st
    where st.id = v_session.support_staff_id and st.active;
  if not found then return null; end if;
  v_context := public.session_context(p_token_hash);
  if v_context is null
    or (v_context->'organization'->>'id')::uuid is distinct from v_grant.organization_id
    or v_context->'account'->>'role' is distinct from 'general_manager' then
    return null;
  end if;
  return v_context || jsonb_build_object('assist', jsonb_build_object(
    'staffId', v_session.support_staff_id, 'staffName', v_staff, 'grantId', v_grant.id,
    'expiresAt', least(v_session.expires_at, v_grant.expires_at)));
end;
$$;
revoke all on function public.assisted_session_context(text) from public, anon, authenticated;
grant execute on function public.assisted_session_context(text) to service_role;

-- Cria (ou reativa) uma conta do suporte e devolve o token do link de primeiro acesso:
--   select public.support_staff_invite('pessoa@rnassessoria.com.br', 'Nome da Pessoa');
-- O link é <origem>/suporte/primeiro-acesso#<token>, vale 24 h e serve uma vez só.
-- Para quem já tem conta, o mesmo comando gera um link de nova senha (o autenticador continua o mesmo;
-- para trocar de celular, passe p_reset_mfa => true). Links anteriores e sessões abertas são encerrados.
create or replace function public.support_staff_invite(p_email text, p_name text default null, p_reset_mfa boolean default false)
returns text
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_email text := lower(trim(p_email));
  v_id bigint;
  v_token text;
begin
  if v_email is null or v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'E-mail inválido.'; end if;
  insert into public.support_staff(email, name) values (v_email, coalesce(nullif(trim(p_name), ''), v_email))
    on conflict (email) do update set active = true, name = coalesce(nullif(trim(p_name), ''), public.support_staff.name)
    returning id into v_id;
  if p_reset_mfa then
    update public.support_staff set mfa_secret_enc = null, mfa_enabled_at = null, mfa_last_step = null where id = v_id;
  end if;
  delete from public.support_setup_tokens where staff_id = v_id;
  delete from public.support_sessions where staff_id = v_id;
  v_token := replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
  insert into public.support_setup_tokens(token_hash, staff_id, expires_at)
    values (encode(sha256(convert_to(v_token, 'UTF8')), 'base64'), v_id, now() + interval '24 hours');
  return v_token;
end;
$$;
revoke all on function public.support_staff_invite(text, text, boolean) from public, anon, authenticated, service_role;

-- Usa o link de primeiro acesso: grava a senha (já com hash da aplicação) e devolve o id da conta,
-- ou null se o link for inválido, vencido ou já usado.
create or replace function public.support_staff_setup(p_token_hash text, p_hash text, p_salt text)
returns bigint
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_id bigint;
begin
  update public.support_setup_tokens t set used_at = now()
    where t.token_hash = p_token_hash and t.used_at is null and t.expires_at > now()
      and exists (select 1 from public.support_staff s where s.id = t.staff_id and s.active)
    returning t.staff_id into v_id;
  if v_id is null then return null; end if;
  update public.support_staff set password_hash = p_hash, password_salt = p_salt where id = v_id;
  delete from public.support_sessions where staff_id = v_id;
  return v_id;
end;
$$;
revoke all on function public.support_staff_setup(text, text, text) from public, anon, authenticated;
grant execute on function public.support_staff_setup(text, text, text) to service_role;

