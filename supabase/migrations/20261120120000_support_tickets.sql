-- Suporte RN Integra, fase 4: chamados abertos pelo botão "Ajuda" do app e respondidos no console.
-- Quem abriu vê o próprio chamado; a gerência vê os chamados da organização; o suporte vê todos.
-- Nada de dados de paciente: o contexto técnico guarda só a tela (sem identificadores), o papel,
-- a versão do sistema e o navegador.

create table if not exists public.support_tickets(
  id bigint generated by default as identity primary key,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  created_by bigint not null references public.users(id),
  subject text not null check (char_length(subject) between 3 and 120),
  category text not null check (category in ('duvida','problema','sugestao','acesso')),
  status text not null default 'open' check (status in ('open','in_progress','waiting_customer','resolved')),
  context jsonb not null default '{}'::jsonb,
  -- Quem falou por último ('customer' ou 'support'): a fila do suporte destaca o que espera resposta.
  last_message_from text not null default 'customer' check (last_message_from in ('customer','support')),
  last_message_at timestamptz not null default now(),
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists support_tickets_org_idx on public.support_tickets(organization_id, last_message_at desc);
create index if not exists support_tickets_status_idx on public.support_tickets(status, last_message_at desc);
create index if not exists support_tickets_author_idx on public.support_tickets(created_by, last_message_at desc);

-- Conversa do chamado: só acrescenta (ninguém edita nem apaga uma mensagem já enviada).
create table if not exists public.support_ticket_messages(
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.support_tickets(id) on delete cascade,
  author_user_id bigint not null references public.users(id),
  from_support boolean not null default false,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);
create index if not exists support_ticket_messages_ticket_idx on public.support_ticket_messages(ticket_id, created_at);

alter table public.support_tickets enable row level security;
alter table public.support_ticket_messages enable row level security;

revoke all on public.support_tickets from public, anon, authenticated;
revoke all on public.support_ticket_messages from public, anon, authenticated;
revoke all on public.support_tickets from service_role;
revoke all on public.support_ticket_messages from service_role;
grant select, insert, update on public.support_tickets to service_role;
grant select, insert on public.support_ticket_messages to service_role;
